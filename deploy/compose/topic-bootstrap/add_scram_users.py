"""Create the lite stack's per-component SCRAM-SHA-512 users on the running broker.

Runs once per `up` as `kafka-users-init`, inside the broker's own network namespace (Compose
`network_mode: service:kafka`), against the broker's LOOPBACK admin listener, which requires a client
certificate (principal CN=tb-lite-users-init; NOT a super user: the broker wrapper grants it ALTER on
the cluster, all AlterUserScramCredentials needs; the certificate is generated by kafka-tls-init).
That ACL also permits Create/DeleteAcls, so the grant is a window: the script asks the broker wrapper
for it (a request file on the `kafka-grant` volume, which holds no secret), provisions, then REVOKES
its own ALTER and withdraws the request (W3-16). The broker wrapper (start-broker.sh) re-grants on every
new request, so a second `docker compose up` (which re-runs this one-shot) provisions again, and removes
the ACL itself as a backstop when the request disappears. Each password is read from the component's own
secret file and goes straight into the AdminClient request: it is never a command-line argument, so it is
visible in no `ps`. Idempotent (an upsert of an existing user re-sets the same password). Stdlib plus
confluent-kafka.
"""

from __future__ import annotations

import logging
import os
import secrets
import signal
import sys
import time
from pathlib import Path
from typing import Any

ITERATIONS = 4096  # Kafka's minimum for SCRAM-SHA-512 is 4096

logging.basicConfig(level=logging.INFO, format='{"level":"%(levelname)s","msg":"%(message)s"}')
log = logging.getLogger("kafka-users-init")

PRINCIPAL = "User:CN=tb-lite-users-init"
GRANT_TIMEOUT_S = 90.0
GRANT_APPLY_RETRIES = 5


def read_users(root: Path, refs: list[str]) -> list[tuple[str, str]]:
    """(username, password) from `<root>/<ref>/{username,password}`; empty values are refused."""
    users: list[tuple[str, str]] = []
    for ref in refs:
        try:
            name = (root / ref / "username").read_text(encoding="utf-8").strip()
            password = (root / ref / "password").read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise SystemExit(f"cannot read secret {ref}") from exc
        if not name or not password:
            raise SystemExit(f"secret {ref} is empty")
        users.append((name, password))
    if len({n for n, _ in users}) != len(users):
        raise SystemExit("two secrets name the same user")
    return users


def admin_config(root: Path, bootstrap: str) -> dict[str, object]:
    return {
        "bootstrap.servers": bootstrap,
        "security.protocol": "SSL",
        "ssl.ca.location": str(root / "tb-lite-kafka-ca" / "ca.crt"),
        "ssl.certificate.location": str(root / "users-init" / "client.crt"),
        "ssl.key.location": str(root / "users-init" / "client.key"),
        "enable.ssl.certificate.verification": True,
        "ssl.endpoint.identification.algorithm": "https",
        "ssl.cipher.suites": "ECDHE+AESGCM:ECDHE+CHACHA20",
    }


def request_grant(grant_dir: Path, timeout: float = GRANT_TIMEOUT_S) -> None:
    """Ask the broker wrapper for the ALTER grant (a random nonce) and wait until it echoes it."""
    nonce = secrets.token_hex(16)
    (grant_dir / "request").write_text(nonce)
    deadline = time.monotonic() + timeout
    while True:
        try:
            if (grant_dir / "granted").read_text() == nonce:
                return
        except OSError:
            pass
        if time.monotonic() > deadline:
            withdraw_request(grant_dir)
            raise SystemExit("the broker did not grant ALTER in time")
        time.sleep(0.5)


def withdraw_request(grant_dir: Path) -> None:
    (grant_dir / "request").unlink(missing_ok=True)


def revoke_own_alter(admin: Any) -> bool:
    """Delete this principal's ALTER on the cluster. True when the request completed."""
    from confluent_kafka.admin import (  # type: ignore[attr-defined]  # deferred import
        AclBindingFilter,
        AclOperation,
        AclPermissionType,
        ResourcePatternType,
        ResourceType,
    )

    flt = AclBindingFilter(
        ResourceType.BROKER,
        "kafka-cluster",
        ResourcePatternType.LITERAL,
        PRINCIPAL,
        "*",
        AclOperation.ALTER,
        AclPermissionType.ALLOW,
    )
    try:
        for future in admin.delete_acls([flt]).values():
            future.result()
    except Exception as exc:  # the class only
        log.error("revoking ALTER failed: %s", type(exc).__name__)
        return False
    log.info("own ALTER on the cluster revoked")
    return True


def _terminate(signum: int, _frame: object) -> None:
    raise SystemExit(128 + signum)


def _is_authorization_failure(exc: Exception) -> bool:
    from confluent_kafka import KafkaError, KafkaException

    arg = exc.args[0] if isinstance(exc, KafkaException) and exc.args else None
    return isinstance(arg, KafkaError) and arg.code() == KafkaError.CLUSTER_AUTHORIZATION_FAILED


def main() -> int:
    from confluent_kafka.admin import (  # type: ignore[attr-defined]  # deferred import
        AdminClient,
        ScramCredentialInfo,
        ScramMechanism,
        UserScramCredentialUpsertion,
    )

    root = Path(os.environ.get("TB_SECRETS_DIR", "/var/run/secrets/tributary"))
    refs = [r for r in os.environ.get("TB_SCRAM_SECRETS", "").split(",") if r]
    if not refs:
        raise SystemExit("TB_SCRAM_SECRETS is required")
    users = read_users(root, refs)
    grant_dir = Path(os.environ.get("TB_GRANT_DIR", "/var/run/tb-grant"))
    # PID 1 ignores SIGTERM unless a handler is installed: turn it into an exit so `finally` revokes.
    signal.signal(signal.SIGTERM, _terminate)
    signal.signal(signal.SIGINT, _terminate)
    admin = AdminClient(admin_config(root, os.environ.get("TB_ADMIN_BOOTSTRAP", "127.0.0.1:9096")))
    info = ScramCredentialInfo(ScramMechanism.SCRAM_SHA_512, ITERATIONS)
    failed = False
    try:
        request_grant(grant_dir)
        for attempt in range(GRANT_APPLY_RETRIES):
            futures = admin.alter_user_scram_credentials(
                [UserScramCredentialUpsertion(name, info, password.encode("utf-8")) for name, password in users]
            )
            failed, not_yet = False, False
            for name, future in futures.items():
                try:
                    future.result()
                except Exception as exc:  # the class only: an exception message must not be trusted with secrets
                    failed = True
                    not_yet = not_yet or _is_authorization_failure(exc)
                    log.error("user %s failed: %s", name, type(exc).__name__)
            if not (failed and not_yet) or attempt == GRANT_APPLY_RETRIES - 1:
                break
            time.sleep(1)  # the broker's authorizer may apply the new ACL a moment after kafka-acls returns
    finally:
        revoked = revoke_own_alter(admin)
        withdraw_request(grant_dir)
    failed = failed or not revoked
    log.info("scram users %s: %d", "FAILED" if failed else "created", len(users))
    if failed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

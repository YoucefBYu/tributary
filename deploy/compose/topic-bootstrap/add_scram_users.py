"""Create the lite stack's per-component SCRAM-SHA-512 users on the running broker.

Runs once per `up` as `kafka-users-init`, inside the broker's own network namespace (Compose
`network_mode: service:kafka`), against the broker's LOOPBACK admin listener, which requires a client
certificate (principal CN=tb-lite-users-init, a super user; the certificate is generated by
kafka-tls-init). Each password is read from the component's own secret file and goes straight into the
AdminClient request: it is never a command-line argument, so it is visible in no `ps`. Idempotent
(an upsert of an existing user re-sets the same password). Stdlib plus confluent-kafka.
"""

from __future__ import annotations

import logging
import os
import sys
from pathlib import Path

ITERATIONS = 4096  # Kafka's minimum for SCRAM-SHA-512 is 4096

logging.basicConfig(level=logging.INFO, format='{"level":"%(levelname)s","msg":"%(message)s"}')
log = logging.getLogger("kafka-users-init")


def read_users(root: Path, refs: list[str]) -> list[tuple[str, str]]:
    """(username, password) from `<root>/<ref>/{username,password}`; empty values are refused."""
    users: list[tuple[str, str]] = []
    for ref in refs:
        try:
            name = (root / ref / "username").read_text(encoding="utf-8").strip()
            password = (root / ref / "password").read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise SystemExit(f"cannot read secret {ref}") from exc
        if not name or not password:
            raise SystemExit(f"secret {ref} is empty")
        users.append((name, password))
    if len({n for n, _ in users}) != len(users):
        raise SystemExit("two secrets name the same user")
    return users


def admin_config(root: Path, bootstrap: str) -> dict[str, object]:
    return {
        "bootstrap.servers": bootstrap,
        "security.protocol": "SSL",
        "ssl.ca.location": str(root / "tb-lite-kafka-ca" / "ca.crt"),
        "ssl.certificate.location": str(root / "users-init" / "client.crt"),
        "ssl.key.location": str(root / "users-init" / "client.key"),
        "enable.ssl.certificate.verification": True,
        "ssl.endpoint.identification.algorithm": "https",
        "ssl.cipher.suites": "ECDHE+AESGCM:ECDHE+CHACHA20",
    }


def main() -> int:
    from confluent_kafka.admin import (  # type: ignore[attr-defined]  # deferred import
        AdminClient,
        ScramCredentialInfo,
        ScramMechanism,
        UserScramCredentialUpsertion,
    )

    root = Path(os.environ.get("TB_SECRETS_DIR", "/var/run/secrets/tributary"))
    refs = [r for r in os.environ.get("TB_SCRAM_SECRETS", "").split(",") if r]
    if not refs:
        raise SystemExit("TB_SCRAM_SECRETS is required")
    users = read_users(root, refs)
    admin = AdminClient(admin_config(root, os.environ.get("TB_ADMIN_BOOTSTRAP", "127.0.0.1:9096")))
    info = ScramCredentialInfo(ScramMechanism.SCRAM_SHA_512, ITERATIONS)
    futures = admin.alter_user_scram_credentials(
        [UserScramCredentialUpsertion(name, info, password.encode("utf-8")) for name, password in users]
    )
    failed = False
    for name, future in futures.items():
        try:
            future.result()
        except Exception as exc:  # the class only: an exception message must not be trusted with secrets
            failed = True
            log.error("user %s failed: %s", name, type(exc).__name__)
    log.info("scram users %s: %d", "FAILED" if failed else "created", len(users))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
